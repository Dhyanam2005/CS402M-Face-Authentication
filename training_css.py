import tensorflow as tf
data_augmentation = keras.Sequential(
    [
        layers.RandomFlip("horizontal", seed=SEED),
        layers.RandomRotation(0.10, fill_mode="reflect", seed=SEED),
        layers.RandomZoom(
            height_factor=(-0.10, 0.15),
            width_factor=(-0.10, 0.15),
            fill_mode="reflect",
            seed=SEED,
        ),
        layers.RandomContrast(0.15, seed=SEED),
        layers.RandomBrightness(
            factor=0.12,
            value_range=(0, 255),
            seed=SEED,
        ),
    ],
    name="data_augmentation",
)

# MobileNetV3Large already includes its required preprocessing.
# Do not add Rescaling(1/255) or mobilenet_v3.preprocess_input.
base_model = tf.keras.applications.MobileNetV3Large(
    input_shape=(IMAGE_SIZE, IMAGE_SIZE, 3),
    include_top=False,
    weights="imagenet",
    include_preprocessing=True,
)

base_model.trainable = False

inputs = keras.Input(
    shape=(IMAGE_SIZE, IMAGE_SIZE, 3),
    name="image",
)

x = data_augmentation(inputs)
x = base_model(x, training=False)
x = layers.GlobalAveragePooling2D(name="global_average_pooling")(x)
x = layers.Dropout(0.40, seed=SEED)(x)

outputs = layers.Dense(
    len(CLASS_NAMES),
    activation="softmax",
    kernel_regularizer=keras.regularizers.l2(1e-4),
    name="classification",
)(x)

model = keras.Model(
    inputs=inputs,
    outputs=outputs,
    name="face_classifier",
)

model.compile(
    optimizer=keras.optimizers.AdamW(
        learning_rate=1e-3,
        weight_decay=1e-4,
    ),
    loss=keras.losses.SparseCategoricalCrossentropy(),
    metrics=[
        keras.metrics.SparseCategoricalAccuracy(name="accuracy"),
        keras.metrics.SparseTopKCategoricalAccuracy(
            k=2,
            name="top_2_accuracy",
        ),
    ],
)

model.summary()

