def get_original_files(class_name, split_name):
    identity_path = CLASS_TO_IDENTITY_PATH[class_name]
    folder = DATASET_ROOT / identity_path / split_name

    assert folder.exists(), f"Missing folder: {folder}"

    # Ignore saved brightness/rotation/flip/noise copies.
