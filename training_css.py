AUTOTUNE = tf.data.AUTOTUNE

def build_dataset(split_name, training=False):
    image_paths = []
    image_labels = []

    for label_index, class_name in enumerate(CLASS_NAMES):
        files = get_original_files(class_name, split_name)

        image_paths.extend([str(file) for file in files])
        image_labels.extend([label_index] * len(files))

    assert image_paths, f"No images found for {split_name}"

    dataset = tf.data.Dataset.from_tensor_slices((image_paths, image_labels))

    if training:
        dataset = dataset.shuffle(
            buffer_size=len(image_paths),
            seed=SEED,
            reshuffle_each_iteration=True,
        )

    def load_and_prepare_image(path, label):
        image_bytes = tf.io.read_file(path)
        image = tf.io.decode_jpeg(image_bytes, channels=3)

        # Keeps aspect ratio and avoids face distortion.
        image = tf.image.resize_with_pad(image, IMAGE_SIZE, IMAGE_SIZE)

        # MobileNetV3 expects RGB values in the normal 0–255 range.
        image = tf.cast(image, tf.float32)

        return image, label

    return (
        dataset
        .map(load_and_prepare_image, num_parallel_calls=AUTOTUNE)
        .batch(BATCH_SIZE)
        .prefetch(AUTOTUNE)
    )

